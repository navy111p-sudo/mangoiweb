/**
 * 🍯 맛보기 한 사람이 하루에 받을 수 있는 판단력 문항 수.
 *   근거 — 레벨 찾기(배치)가 6문항이라(judgment.html), 그것을 끝내고도 몇 문제 더 풀어
 *   «어떤 도구인지» 를 알기에 충분한 값입니다. 「하루 종일 쓰라」는 값이 아닙니다.
 *   ⛔ 이 숫자를 화면에 복제하지 마세요 — 서버가 응답의 `limit` 으로 알려 줍니다.
 *   ⚠️ 로그인한 학생에게는 걸리지 않습니다.
 */
export const SAMPLE_SCENARIO_CAP = 12;

/**
 * 오늘 `used` 번 받은 게스트에게 한 번 더 줘도 되는가.
 *   ⚠️ 못 세면(KV 실패·이상한 값) **막지 않습니다** — 그러면 «맛보기를 열기 전»(게스트가
 *      이미 통과하던 상태)과 같아질 뿐이고, 고장 난 가드가 맛보기를 영구히 막는 쪽이 더 나쁩니다.
 *      같은 파일의 judg:ic:rl 가드와 같은 방향입니다.
 */
export function sampleScenarioAllowed(used: any, cap: number = SAMPLE_SCENARIO_CAP): boolean {
  const n = Number(used);
  if (!isFinite(n) || n < 0) return true;   // 모르면 막지 않는다(fail-open)
  return n < cap;
}
