// 🧹 «뜻» 카드에 내보내도 되는 한국어인가 (2026-10-02)
//
//   발단: 사장님 제보 — A.i 말하기(웜업) «뜻» 자리에 'ㅋㅋㅋㅋ' 같은 글자가 나왔다.
//   원인: /api/translate(mode:'learn') 의 성공 판정이 `hasHangul()` 하나였는데,
//         그 함수는 «한글 자모»(ㄱ-ㅎ·ㅏ-ㅣ)도 한글로 센다. 그래서 모델이 'ㅋㅋㅋㅋ' 만
//         돌려줘도 «번역 성공» 이 되어 화면에 그려지고, KV 에 180일 저장됐다.
//
//   ✅ 규칙: 자모 반복(ㅋㅋ·ㅎㅎ·ㅠㅠ…)을 걷어낸 뒤 «완성 한글 음절» 이 하나라도 남아야 한다.
//   ✅ 이 판정은 «저장된 값을 읽을 때» 도 쓴다 — 그래서 캐시 이름(trl2:)을 바꾸지 않고도
//      이미 굳은 이상한 뜻만 골라 버리고, 멀쩡한 의역 캐시는 그대로 산다.
//   ⛔ learn 모드에만 쓴다 — 채팅 번역(chat)에서 「ㅋㅋ 좋아요」는 사람이 쓴 정상 문장이다.
//   이 파일은 import 가 없다 — 하니스가 그대로 불러 «실제로 돌려서» 검증한다.
// ═══════════════════════════════════════════════════════════════════════

/** 자모만으로 된 덩어리(2글자 이상) — ㅋㅋ, ㅎㅎㅎ, ㅠㅠ, ㄷㄷ … */
const JAMO_RUN = /[ㄱ-ㆎ]{2,}/g;

/** 뜻 문장에서 자모 반복을 걷어내고 공백을 정리한다. */
export function stripJamoRuns(s: unknown): string {
  return String(s == null ? '' : s).replace(JAMO_RUN, ' ').replace(/\s{2,}/g, ' ').trim();
}

/**
 * «뜻» 카드에 그대로 보여 줘도 되는가.
 * - 비었으면 ✕
 * - 자모 반복을 걷어낸 뒤 완성 음절(가-힣)이 하나도 없으면 ✕ ('ㅋㅋㅋㅋ', 'ㅠ', '...')
 * - 원문(영어)과 같으면 ✕ (번역이 안 된 것)
 */
export function isUsableKoMeaning(out: unknown, src?: unknown): boolean {
  const o = stripJamoRuns(out);
  if (!o) return false;
  if (!/[가-힣]/.test(o)) return false;
  if (src != null && o === String(src).trim()) return false;
  return true;
}
