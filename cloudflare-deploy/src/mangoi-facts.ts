/**
 * 사용자 문장에서 FAQ 주제를 찾아 사람이 쓴 답을 최대 `max` 개 돌려줍니다.
 * 한글 NFD(자모 분리) 입력에서도 매칭되도록 NFC 로 정규화합니다.
 */
export function matchMangoiFaq(userMsg: string, max = 2): string[] {
  const msg = String(userMsg || '').normalize('NFC');
  const hits: string[] = [];
  for (const f of MANGOI_FAQ) {
    if (f.kw.some((k) => msg.indexOf(k) >= 0)) {
      hits.push(f.a);
      if (hits.length >= max) break;
    }
  }
  return hits;
}
