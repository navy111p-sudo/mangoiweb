/**
 * 영어 말풍선에 «모델이 스스로 끼워 넣은 한국어» 를 떼어낸다 (2026-09-01)
 *
 * 발단 — 사장님 제보. AI 영어친구 화면에서 이런 답이 나왔습니다:
 *   Wow! What's your favorite kind of candy? «너의 가장 좋아하는 캔디는?»
 *   Yay! Me too! Do you have a favorite color? «너의 가장 좋아하는 색깔은?»
 *   「한국어는 뜻 버튼을 눌러야 나오는데 이유가 뭐지?」
 *
 * 원인 — 프롬프트 어디에도 «번역해 주라» 는 지시가 없습니다. 모델이 «친절하게» 덧붙인 것입니다.
 *   실측: src/api-ai.ts 의 chat-friend 시스템 프롬프트에서 한국어가 허용된 자리는
 *   문법 팁 하나뿐입니다(아래 TIP). 화면(ai-friend.html)은 서버가 준 글자를 그대로 그립니다 —
 *   즉 화면이 붙인 것이 아니라 답변 자체에 들어 있었습니다.
 *   이 저장소가 반복해 확인한 그대로입니다 — 「지시만으로는 안 지켜진다」.
 *   선례가 바로 옆에 있습니다: 2026-07-27 「한국어 팁에 한자가 섞인다」 → aiFriendStripHanzi.
 *
 * 왜 그냥 두면 안 되나 — 두 가지가 함께 망가집니다.
 *   1) 뜻 버튼·자막 3단계(전체/가리기/끄기)의 «영어를 먼저 읽어 보게 한다» 는 설계가 무너집니다.
 *      한국어가 옆에 있으면 아무도 영어를 읽지 않습니다.
 *   2) 「다시 듣기」가 그 한국어까지 영어 TTS 로 읽습니다 — 소리가 뭉개집니다
 *      (CLAUDE.md 「한국어를 영어 말풍선에 섞지 마세요」).
 *
 * 문장을 «고쳐 쓰지» 않습니다. 하는 일은 «덧붙은 한국어 덩어리를 떼는 것» 뿐이고,
 * 떼고 나면 원래의 영어 문장이 그대로 남습니다(아이가 따라 읽을 문장을 지어내지 않습니다).
 * 문법 팁은 «일부러 넣은 기능» 이라 남깁니다 — 그것까지 떼면 2026-07-27 에 만든 기능이
 * 조용히 사라집니다.
 * 떼고 나서 영어가 하나도 안 남으면 «원문 그대로» 돌려줍니다 — 빈 말풍선이 더 나쁩니다.
 *
 * 이 파일은 import 가 하나도 없습니다 — 하니스가 그대로 불러 «실제로 돌려서» 검증합니다.
 */

const HANGUL = /[가-힣ㄱ-ㆎ]/;

/** 문법 팁 — 전구 이모지로 시작하는 그 한 자리만 한국어가 허용된다 */
const TIP = /\(?\s*💡[^\n)]*\)?/g;

/** 자리표시 — 한글도 영문자도 아닌 모양이라야 아래 규칙에 다시 걸리지 않는다 */
const SLOT = (i: number) => '' + i + '';

/**
 * 영어 답변에서 «덧붙은 한국어» 를 뗀다. 문법 팁은 남긴다.
 * 뗄 것이 없으면 원문을 그대로 돌려준다.
 */
export function stripAddedKorean(reply: unknown): string {
  const src = String(reply || '');
  if (!HANGUL.test(src)) return src;

  /* 팁은 «자리를 비워 두고» 나중에 되돌려 놓는다 — 팁 안의 한국어까지 떼지 않기 위해서다 */
  const tips: string[] = [];
  let r = src.replace(TIP, (m) => {
    tips.push(m);
    return SLOT(tips.length - 1);
  });

  /* 1) 괄호·따옴표류로 «감싼» 한국어 덩어리를 통째로 뗀다.
        모델이 번역을 넣을 때 쓰는 모양이다 — 겹화살괄호·괄호·대괄호·따옴표. */
  r = r.replace(/[«‹][^«»‹›\n]*[가-힣ㄱ-ㆎ][^«»‹›\n]*[»›]/g, ' ');
  r = r.replace(/[([{][^)\]}\n]*[가-힣ㄱ-ㆎ][^)\]}\n]*[)\]}]/g, ' ');
  r = r.replace(/["“”][^"“”\n]*[가-힣ㄱ-ㆎ][^"“”\n]*["“”]/g, ' ');

  /* 2) 감싸지 않은 채 남은 한국어 조각 — 이어지는 한국어·숫자·구두점을 함께 뗀다.
        앞뒤 영어를 먹지 않도록 «한글로 시작하는 덩어리» 만 잡는다. */
  r = r.replace(/[가-힣ㄱ-ㆎ][가-힣ㄱ-ㆎ0-9 \t.,!?~·…'"-]*/g, ' ');

  /* 팁 되돌리기 */
  r = r.replace(/(\d+)/g, (_m, i) => tips[Number(i)] || '');

  /* 뗀 자리에 남은 빈 괄호·중복 공백·뜬 구두점 정리 */
  r = r.replace(/\(\s*\)|\[\s*\]|\{\s*\}|«\s*»/g, ' ')
    .replace(/[ \t]{2,}/g, ' ')
    .replace(/[ \t]+([.,!?])/g, '$1')
    .replace(/[ \t]+\n/g, '\n')
    .trim();

  /* 영어가 하나도 안 남았으면 손대지 않는다 — 빈 말풍선이 더 나쁘다.
     (학생이 한국어로 물어 모델이 한국어로만 답한 경우가 여기 걸린다.) */
  if (!/[A-Za-z]/.test(r.replace(TIP, ''))) return src;
  return r;
}

/** 「이 답에 덧붙은 한국어가 있나」 — 로그·하니스용. 문법 팁은 세지 않는다. */
export function hasAddedKorean(reply: unknown): boolean {
  const src = String(reply || '');
  return HANGUL.test(src.replace(TIP, '')) && stripAddedKorean(src) !== src;
}
