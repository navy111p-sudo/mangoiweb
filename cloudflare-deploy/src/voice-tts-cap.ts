/**
 * 한 IP 가 하루에 Azure 성우를 부를 수 있는 횟수.
 *
 * 📐 근거 — 세는 단위가 **IP** 라 «한 사람» 이 아니라 «한 회선» 입니다.
 *    학원 한 곳이 공인 IP 하나를 나눠 쓰면 그 IP 로 전부 합산됩니다
 *    (녹화 상한이 30 → 300 으로 올라간 바로 그 이유 — 필리핀 사무실 강사 21명).
 *    ⚠️ 학생 IP 는 이 저장소 어디에도 기록되지 않아 «한 IP 에 몇 명이 붙는가» 를
 *       **못 쟀습니다.** 그래서 녹화 선례와 같은 값으로 넉넉히 둡니다.
 *    한 세션 ≈ AI 발화 10~15회이므로 300 이면 한 회선에서 20명이 하루 한 세션씩
 *    돌려도 안 걸립니다. 남용은 수천 건 단위로 들어오므로 300 으로도 그대로 막힙니다.
 *
 * 💰 이 값이 정하는 최악 — 300건 × 6.3원 ≈ **하루 1,890원 / IP**.
 *
 * ✅ 조이거나 푸는 것은 **이 숫자 한 줄**입니다(사람이 정할 일).
 * ⛔ 이 숫자를 화면에 복제하지 마세요 — 화면은 걸렸는지조차 알 필요가 없습니다
 *    (걸리면 «예전 경로» 로 내려가 소리는 그대로 납니다 — 아래 설명).
 */
export const AZURE_TTS_MAX_PER_IP_DAY = 300;

/**
 * 오늘 `used` 번 부른 이 IP 에게 한 번 더 허락할 것인가.
 *
 * ⚠️ 못 세면(KV 장애·이상한 값) **막지 않습니다.** 그러면 «상한을 걸기 전» 과 같아질 뿐이고,
 *    고장 난 가드가 중국어 남자 목소리를 영구히 막는 쪽이 더 나쁩니다
 *    (`judgment-sample-gate.ts`·`recording-dup-guard.ts` 와 같은 방향).
 */
export function azureTtsAllowed(used: any, cap: number = AZURE_TTS_MAX_PER_IP_DAY): boolean {
  const n = Number(used);
  if (!isFinite(n) || n < 0) return true;   // 모르면 막지 않는다(fail-open)
  return n < cap;
}

/**
 * 그 IP 의 «오늘» 카운터 키. 하루는 **KST 자정**에 새로 시작합니다.
 *
 * ⚠️ 경계에서 리셋되므로 자정을 낀 짧은 시간에는 최대 두 배(600건 ≈ 3,780원)까지
 *    나갈 수 있습니다 — 아는 채로 둔 맞바꿈입니다(굴러가는 창으로 만들면 KV 쓰기가
 *    두 배가 되고, 막아 봐야 아끼는 돈이 1,890원입니다).
 * ⚠️ 시각을 모르면 0번 칸으로 떨어집니다 — 그래도 «세기는» 하므로 상한이 살아 있습니다.
 */
export function azureTtsCapKey(ip: any, nowMs: any): string {
  const who = String(ip || '').trim() || 'unknown';
  const t = Number(nowMs);
  const day = isFinite(t) && t > 0 ? Math.floor((t + 9 * 3600000) / 86400000) : 0;
  return 'ttsazcap:' + who + ':' + day;
}
